import type { StopCategory } from './commands';
import type { GoalieRotation, SpecialUnit } from './sports/hockey';
import type {
  CapCharge,
  Contract,
  CardEffects,
  DraftProspect,
  FinanceLines,
  GameResult,
  Department,
  GmProfile,
  InternationalTournament,
  StaffProfile,
  OwnerCard,
  OwnerStanding,
  Player,
  TeamPlan,
  PlayerId,
  PlayoffSeries,
  RetainedSalary,
  Team,
  ScheduledGame,
  TeamFans,
  TeamId,
  FreeAgentOffer,
  TradeOffer,
} from './domain';

/**
 * Everything that happens in a league is an event. The sim produces events, a reducer
 * applies them to state, the data layer stores them, and the UI (news feed, Home "To do",
 * history) reads them. Events are plain, serializable data: they cross the worker, IPC and
 * (later) the network unchanged.
 *
 * Add a new event kind here first, then handle it in the sim reducer. TypeScript will
 * point at every switch that forgot it.
 */

/** In-game date: season (e.g. 2027 = the 2026-27 season) + day index from opening night. */
export interface GameDate {
  season: number;
  day: number;
}

/** How loudly an event should surface. "Sim until it matters" stops on `major` for your team. */
export type Importance = 'minor' | 'notable' | 'major';

export type SeasonPhase = 'preseason' | 'regular' | 'playoffs' | 'offseason';

export type TeamStatus = 'contender' | 'buyer' | 'bubble' | 'seller' | 'rebuilder' | 'crisis';

interface EventBase {
  /** Unique, sortable id. Generated by the sim from the seed, never from the clock. */
  id: string;
  date: GameDate;
  importance: Importance;
  /** Teams this event concerns; drives "my team" filters. */
  teamIds: TeamId[];
  playerIds?: PlayerId[];
}

export type LeagueEvent =
  /** End of a sim day: new date + RNG position, so every copy of the state stays identical. */
  | (EventBase & { kind: 'clock.advanced'; to: GameDate; rngState: number })
  | (EventBase & { kind: 'game.final'; result: GameResult })
  | (EventBase & { kind: 'series.started'; series: PlayoffSeries })
  | (EventBase & { kind: 'series.won'; seriesId: string; winnerTeamId: TeamId })
  | (EventBase & { kind: 'champion.crowned'; championTeamId: TeamId })
  /** Offseason: one batch for the whole league, so the log holds one entry per year, not per player. */
  | (EventBase & {
      kind: 'players.developed';
      changes: { playerId: PlayerId; ratings: Record<string, number>; potential: number }[];
    })
  | (EventBase & { kind: 'player.retired'; playerId: PlayerId })
  /** Bought out: the player becomes a free agent and the team carries `charges` as dead cap. */
  | (EventBase & {
      kind: 'contract.boughtOut';
      playerId: PlayerId;
      teamId: TeamId;
      charges: CapCharge[];
    })
  /** Hurt in a game: out until day `until` (first day back) of the current season. */
  | (EventBase & { kind: 'player.injured'; playerId: PlayerId; days: number; until: number })
  /** In-season extension: `contract` starts when his current deal ends. */
  | (EventBase & {
      kind: 'contract.extended';
      playerId: PlayerId;
      teamId: TeamId;
      contract: Contract;
    })
  /** Contract ran out: the player becomes a free agent. */
  /** `rightsTeamId`: a restricted free agent; that team may match another team's offer sheet. */
  | (EventBase & { kind: 'contract.expired'; playerId: PlayerId; rightsTeamId?: TeamId })
  /**
   * A new player enters the league through the draft (the event carries the whole player).
   * `round` and `pick` are 0 for an undrafted free agent signed to fill a roster. `via`: the
   * team the pick belonged to, when another team made it (traded or protected). With
   * `prospect`, a pick: he goes to his team's prospect pool unsigned (`Prospect`).
   */
  | (EventBase & {
      kind: 'player.drafted';
      player: Player;
      round: number;
      pick: number;
      via?: TeamId;
      prospect?: { league: string; rightsEnd: number };
    })
  /** A prospect signs his entry deal: he leaves the pool and joins his team. */
  | (EventBase & {
      kind: 'prospect.signed';
      playerId: PlayerId;
      teamId: TeamId;
      contract: Contract;
    })
  /** His team's rights ran out unsigned: he leaves the pool and is a free agent. */
  | (EventBase & { kind: 'prospect.released'; playerId: PlayerId })
  /**
   * Re-signing, free agency or an undrafted free agent: player joins `teamId` on `contract`.
   * `staying`: he re-signs with the team whose contract just expired, so his time there carries on.
   */
  | (EventBase & {
      kind: 'player.signed';
      playerId: PlayerId;
      teamId: TeamId;
      contract: Contract;
      staying?: true;
      /** An offer sheet signed him away: these draft picks go to the team that held his rights. */
      compensation?: { toTeamId: TeamId; picks: string[] };
      /** His offer promised him the top role at his position (checked in his first regular season). */
      promiseRole?: true;
    })
  /**
   * End of the playoffs: performance bonuses earned this season, and the part of each team's
   * that went over the cap, charged to next season's cap.
   */
  | (EventBase & {
      kind: 'bonuses.paid';
      season: number;
      paid: { playerId: PlayerId; teamId: TeamId; amount: number }[];
      charges: CapCharge[];
    })
  /**
   * A team's cash for a month (or the playoffs) settles: revenue in, costs out, over `homeDates`
   * home dates. `fans`: the team's fans after the month.
   */
  | (EventBase &
      ({
        kind: 'finance.settled';
        teamId: TeamId;
        homeDates: number;
        fans: TeamFans;
      } & FinanceLines))
  /** An owner meeting (preseason objectives, deadline check-in, season-end review): his standing after it. */
  | (EventBase & {
      kind: 'owner.meeting';
      teamId: TeamId;
      meeting: 'preseason' | 'deadline' | 'review';
      owner: OwnerStanding;
    })
  /** A month of results moved the owner's confidence in the GM. */
  | (EventBase & { kind: 'owner.confidenceMoved'; teamId: TeamId; confidence: number })
  /** An AI owner's frustration made the news (once a season). */
  | (EventBase & { kind: 'owner.frustrated'; teamId: TeamId })
  /** The owner puts a decision to a human GM. */
  | (EventBase & { kind: 'owner.cardOpened'; card: OwnerCard })
  /** A card was answered (by an AI GM, a human, or by default at the next meeting): `effects` apply. */
  | (EventBase & {
      kind: 'owner.cardAnswered';
      teamId: TeamId;
      cardId: string;
      cardKind: OwnerCard['kind'];
      option: OwnerCard['options'][number]['key'];
      effects: CardEffects;
    })
  /** A project is done: the arena now seats `capacity`, and fan interest moves by `fanInterest`. */
  | (EventBase & {
      kind: 'project.finished';
      teamId: TeamId;
      projectId: string;
      capacity: number;
      fanInterest: number;
    })
  /** A team's ticket price policy changed (see `TICKET_STEPS`); the next settlement uses it. */
  | (EventBase & { kind: 'finance.ticketPriceSet'; teamId: TeamId; pct: number })
  /** End of season: who won an award. `playerId` is absent for team awards (champion). */
  | (EventBase & {
      kind: 'award.given';
      award: string;
      season: number;
      teamId: TeamId;
      playerId?: PlayerId;
    })
  /** Late in the summer of a tournament season: the international tournament was played. */
  | (EventBase & { kind: 'international.played'; tournament: InternationalTournament })
  /** The playoffs are over: next draft's class, with scouted ranges, and the lottery's round-one order. */
  | (EventBase & {
      kind: 'draft.classAnnounced';
      prospects: DraftProspect[];
      firstRound?: TeamId[];
    })
  /** A team ranked the prospects it wants; its picks follow this order. */
  | (EventBase & { kind: 'draft.boardSet'; teamId: TeamId; order: PlayerId[] })
  /** The live draft opens (contracts have run out); picks follow one at a time. */
  | (EventBase & { kind: 'draft.started' })
  /** End of a regular season: every player's stat line, kept for career stats (sport-defined keys). */
  | (EventBase & {
      kind: 'stats.archived';
      season: number;
      lines: { playerId: PlayerId; teamId: TeamId | null; stats: Record<string, number> }[];
    })
  /** A team's depth order changed (lines). */
  | (EventBase & { kind: 'lines.set'; teamId: TeamId; order: PlayerId[] })
  /** A team's power-play or penalty-kill unit changed (empty = auto). */
  | (EventBase & { kind: 'units.set'; teamId: TeamId; unit: SpecialUnit; playerIds: PlayerId[] })
  /** A human team set (or cleared) a player's summer training focus. */
  | (EventBase & {
      kind: 'training.planSet';
      teamId: TeamId;
      playerId: PlayerId;
      focus: string | null;
    })
  /** A human team listed a player as available (or took him off the block). */
  | (EventBase & { kind: 'trade.blockSet'; teamId: TeamId; playerId: PlayerId; onBlock: boolean })
  /** A team changed how its goalies share starts. */
  | (EventBase & { kind: 'goalies.rotationSet'; teamId: TeamId; rotation: GoalieRotation })
  /** A team made a free agent an offer (replaces its earlier one; `raise`: an AI team trailing in the race); he answers on his decision day. */
  | (EventBase & { kind: 'freeAgency.offered'; offer: FreeAgentOffer; raise?: true })
  /**
   * His agent's answer to an offer under his line: the lowest salary he signs for at its term,
   * clause and bonus (`counter`) or, when no salary gets him there, the factor holding him back;
   * and the rounds of talks `teamId` has left (0: broken off until free agency opens or the season
   * starts, so no counter).
   */
  | (EventBase & {
      kind: 'contract.countered';
      playerId: PlayerId;
      teamId: TeamId;
      rounds: number;
      counter?: number;
      holdsBack?: 'winning' | 'role' | 'term';
    })
  /** A new market day in the summer's free agency (1 on the first after it opens). */
  | (EventBase & { kind: 'freeAgency.dayPassed'; day: number })
  /** An offer sheet to a restricted free agent: the team holding his rights may match it or not. */
  | (EventBase & { kind: 'freeAgency.sheetReceived'; offer: FreeAgentOffer })
  /** A sheet that cannot be signed any more (cap room moved): it is gone. */
  | (EventBase & { kind: 'freeAgency.sheetDropped'; playerId: PlayerId })
  /** The offseason's free-agency window opened (closes when the next season starts). */
  | (EventBase & { kind: 'freeAgency.opened' })
  /** A new season: fresh schedule, clock back to the first day of camp, results cleared. */
  | (EventBase & {
      kind: 'season.started';
      season: number;
      schedule: ScheduledGame[];
      rngState: number;
      /** The day it opens on, -preseasonDays (absent in old saves: day 0, opening night). */
      day?: number;
      /** Each team's form this season, rating points (absent in old saves: none). */
      form?: Record<TeamId, number>;
    })
  /** A trade went through: `give` moved from `fromTeamId` to `toTeamId`, `get` the other way. */
  | (EventBase & {
      kind: 'trade.completed';
      fromTeamId: TeamId;
      toTeamId: TeamId;
      give: PlayerId[];
      get: PlayerId[];
      retained?: RetainedSalary[];
      givePicks?: string[];
      getPicks?: string[];
      /** Top-N protection on the picks `fromTeamId` gave (it keeps one that lands that high). */
      protectTop?: number;
    })
  /** An unhappy player asks his (human) team to trade him. */
  | (EventBase & { kind: 'player.tradeRequested'; playerId: PlayerId; teamId: TeamId })
  /** A trade request ends: withdrawn after a talk, or he was traded. */
  | (EventBase & { kind: 'player.tradeRequestEnded'; playerId: PlayerId; withdrawn: boolean })
  /** A player unhappy with his role (he sits well down the depth order for his rating) asks for more. */
  | (EventBase & { kind: 'player.disputeStarted'; playerId: PlayerId; teamId: TeamId })
  /** The role promised when he signed came due: `kept` if he is first at his position (else a dispute opens). */
  | (EventBase & { kind: 'player.rolePromiseDue'; playerId: PlayerId; kept: boolean })
  /** The GM put him on the block: the dispute stays open while he is listed (unlisted: he asks out). */
  | (EventBase & { kind: 'player.disputeListed'; playerId: PlayerId })
  /** The GM promised him a bigger role by day `until` (of this season). */
  | (EventBase & { kind: 'player.disputePromised'; playerId: PlayerId; until: number })
  /** Settled: he accepted (`settled`), the GM kept his word (`kept`), or it is over without peace (`request`: he asks out; `listed`: he is on the block). */
  | (EventBase & {
      kind: 'player.disputeEnded';
      playerId: PlayerId;
      outcome: 'settled' | 'kept' | 'request' | 'listed';
    })
  /** A player under contract refuses to report until he is paid, talked round or traded. */
  | (EventBase & { kind: 'player.holdoutStarted'; playerId: PlayerId; teamId: TeamId })
  /** A holdout ends with the player back at work (`talked`: after a talk with the GM). */
  | (EventBase & { kind: 'player.holdoutEnded'; playerId: PlayerId; talked: boolean })
  /** A player agreed to waive his no-trade clause for a trade (the clause is gone). */
  | (EventBase & { kind: 'player.noTradeWaived'; playerId: PlayerId })
  /** A young player on a human team broke out, for `season`: Home asks if you talk extension now. */
  | (EventBase & { kind: 'player.brokeOut'; playerId: PlayerId; teamId: TeamId; season: number })
  /** An AI GM offers a human team a trade (see `TradeOffer`). */
  | (EventBase & { kind: 'trade.offered'; offer: TradeOffer })
  /** An offer is gone: accepted (a `trade.completed` follows), declined or expired. */
  | (EventBase & { kind: 'trade.offerClosed'; offerId: string; accepted: boolean })
  | (EventBase & { kind: 'team.controlChanged'; teamId: TeamId; userControlled: boolean })
  /** A team's identity changed (the identity editor). */
  | (EventBase & {
      kind: 'team.renamed';
      teamId: TeamId;
      city: string;
      name: string;
      abbreviation: string;
    })
  /** A franchise moved: new identity and market size, and its fans lost `fanLoss` interest. */
  | (EventBase & {
      kind: 'team.relocated';
      teamId: TeamId;
      city: string;
      name: string;
      abbreviation: string;
      market: number;
      fanLoss: number;
    })
  /** An expansion team joined the league and took `taken` from the other teams. */
  | (EventBase & { kind: 'team.expanded'; team: Team; taken: PlayerId[] })
  /** The commissioner moved a player to `toTeamId` (null: free agency, his contract voided). */
  | (EventBase & { kind: 'player.moved'; playerId: PlayerId; toTeamId: TeamId | null })
  /** An AI team has a new GM (the old one was fired or moved on). */
  | (EventBase & { kind: 'team.gmChanged'; teamId: TeamId; gm: GmProfile; fired: boolean })
  /** A department head left (`poached`: hired away after a good season) and `head` took over. */
  | (EventBase & {
      kind: 'staff.hired';
      teamId: TeamId;
      department: Department;
      head: StaffProfile;
      poached: boolean;
    })
  /** A human GM fired a department head: `head`, an interim, took over and `severance` left the cash. */
  | (EventBase & {
      kind: 'staff.fired';
      teamId: TeamId;
      department: Department;
      head: StaffProfile;
      severance: number;
    })
  /** The owner fired a human GM at the review: the team goes to `gm`, an AI GM, and you are out of work. */
  | (EventBase & { kind: 'career.fired'; teamId: TeamId; gm: GmProfile })
  /** Teams with a vacancy that want the GM who is out of work (replaces any earlier ones). */
  | (EventBase & { kind: 'career.offers'; offers: TeamId[] })
  /** The GM out of work took a job: he runs `teamId` now, with a new owner's honeymoon. */
  | (EventBase & { kind: 'career.hired'; teamId: TeamId })
  /** A save option changed: "can be fired" or the sim bar's stop filter (only the one that changed). */
  | (EventBase & { kind: 'league.optionSet'; canBeFired?: boolean; stopOn?: StopCategory[] })
  /** An AI GM sets a new plan for his team (contend, retool, rebuild). */
  | (EventBase & { kind: 'team.planChanged'; teamId: TeamId; plan: TeamPlan })
  | (EventBase & { kind: 'season.phaseChanged'; from: SeasonPhase; to: SeasonPhase })
  | (EventBase & { kind: 'team.statusChanged'; teamId: TeamId; from: TeamStatus; to: TeamStatus })
  | (EventBase & {
      kind: 'news.posted';
      headline: string;
      /** The player the line is about (set whenever `params.player` names one), for his face. */
      playerId?: PlayerId;
      /** The person speaking (his name kept on the post, so a fired coach keeps his face). */
      by?: { role: 'gm' | 'coach' | 'owner'; name: string };
      body?: string;
      params?: Record<string, string | number>;
    });
