import type { GameResult, PlayerId, PlayoffSeries, TeamId } from './domain';

/**
 * Everything that happens in a league is an event. The sim produces events, a reducer
 * applies them to state, the data layer stores them, and the UI (news feed, Home "To do",
 * history) reads them. Events are plain, serializable data: they cross the worker, IPC and
 * (later) the network unchanged.
 *
 * Add a new event kind here first, then handle it in the sim reducer. TypeScript will
 * point at every switch that forgot it.
 */

/** In-game date: season (e.g. 2027 = the 2026-27 season) + day index from opening night. */
export interface GameDate {
  season: number;
  day: number;
}

/** How loudly an event should surface. "Sim until it matters" stops on `major` for your team. */
export type Importance = 'minor' | 'notable' | 'major';

export type SeasonPhase = 'preseason' | 'regular' | 'playoffs' | 'offseason';

export type TeamStatus = 'contender' | 'buyer' | 'bubble' | 'seller' | 'rebuilder' | 'crisis';

interface EventBase {
  /** Unique, sortable id. Generated by the sim from the seed, never from the clock. */
  id: string;
  date: GameDate;
  importance: Importance;
  /** Teams this event concerns; drives "my team" filters. */
  teamIds: TeamId[];
  playerIds?: PlayerId[];
}

export type LeagueEvent =
  /** End of a sim day: new date + RNG position, so every copy of the state stays identical. */
  | (EventBase & { kind: 'clock.advanced'; to: GameDate; rngState: number })
  | (EventBase & { kind: 'game.final'; result: GameResult })
  | (EventBase & { kind: 'series.started'; series: PlayoffSeries })
  | (EventBase & { kind: 'series.won'; seriesId: string; winnerTeamId: TeamId })
  | (EventBase & { kind: 'champion.crowned'; championTeamId: TeamId })
  | (EventBase & { kind: 'team.controlChanged'; teamId: TeamId; userControlled: boolean })
  | (EventBase & { kind: 'season.phaseChanged'; from: SeasonPhase; to: SeasonPhase })
  | (EventBase & { kind: 'team.statusChanged'; teamId: TeamId; from: TeamStatus; to: TeamStatus })
  | (EventBase & {
      kind: 'news.posted';
      headline: string;
      body?: string;
      params?: Record<string, string | number>;
    });

export type LeagueEventKind = LeagueEvent['kind'];
