import { writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { GOALIE_RATINGS, SKATER_RATINGS } from '@gm/shared';
import {
  createLeague,
  defaultContext,
  FULL_SAMPLE,
  handleCommand,
  hockeySeasonStats,
  ratingGroup,
  statFeatures,
  type RatingFit,
  type RatingGroup,
  type RatingsToStatsTable,
  type StatsToRatingsTable,
} from '@gm/sim';
import { fitLinear, mean, sd } from './stats';

/**
 * Fits the stats-to-ratings table (packages/sim/src/sports/hockey/ratingsFromStatsTable.ts)
 * on the sim itself: plays one regular season in each of many fresh leagues and fits every
 * hidden rating on the stat lines it produced. One league in five is held out to measure R²
 * and the error; the table is then refit on all leagues. The same seasons fit the other way
 * round too: per-game rates from ratings (ratingsToStatsTable.ts), for lower-league lines.
 *
 *   pnpm ratings:fit              # 120 leagues, about 2 minutes
 *   pnpm ratings:fit --leagues 40
 *
 * Rerun after any change to the game sim or player generation, and commit the new table.
 */
const args = process.argv.slice(2);
const leagues = Number(args[args.indexOf('--leagues') + 1]) || 120;
const ctx = defaultContext();
const seasonGames = ctx.ruleset.season.gamesPerTeam;

interface Row {
  league: number;
  x: number[];
  ratings: Record<string, number>;
}
const rows: Record<RatingGroup, Row[]> = { F: [], D: [], G: [] };
/** The same skater seasons with penalty-kill time and penalty minutes added. */
const specialRows: Record<'F' | 'D', Row[]> = { F: [], D: [] };
/** Ratings to stats: skaters' log goals and assists a game (half a goal added), goalies' save %. */
const rates: Record<RatingGroup, { ratings: Record<string, number>; y: Record<string, number> }[]> =
  { F: [], D: [], G: [] };
const started = performance.now();
for (let l = 0; l < leagues; l++) {
  const state = createLeague(10_000 + l, ctx);
  const res = handleCommand(
    state,
    { kind: 'sim.advance', days: ctx.ruleset.season.calendar.regularSeasonDays - state.date.day },
    { id: 'lab', controls: [], can: ['advance'] },
    ctx,
  );
  if (!res.ok) throw new Error(res.error.message);
  const { skaters, goalies } = hockeySeasonStats(Object.values(state.results));
  for (const p of Object.values(state.players)) {
    const totals = skaters.get(p.id) ?? goalies.get(p.id);
    if (!totals) continue;
    const { features, special, share } = statFeatures(p.position, totals, seasonGames);
    // Fit on full samples only; smaller ones are shrunk at estimate time.
    if (share < 1) continue;
    const g = ratingGroup(p.position);
    rows[g].push({ league: l, x: features, ratings: p.ratings });
    if (special && g !== 'G')
      specialRows[g].push({ league: l, x: [...features, ...special], ratings: p.ratings });
    const s = skaters.get(p.id);
    const gl = goalies.get(p.id);
    const y = s
      ? { goals: Math.log((s.goals + 0.5) / s.gp), assists: Math.log((s.assists + 0.5) / s.gp) }
      : { savePct: gl!.saves / gl!.shotsAgainst };
    rates[g].push({ ratings: p.ratings, y });
  }
}

/** Writes a generated table module (type import, name, JSON value), formatted with prettier. */
const writeTable = (
  file: string,
  typeImport: string,
  name: string,
  type: string,
  table: object,
) => {
  const out = new URL(`../../../packages/sim/src/sports/hockey/${file}`, import.meta.url);
  writeFileSync(
    out,
    `import type { ${type} } from '${typeImport}';

/** Generated by \`pnpm ratings:fit\` (tools/balance-lab/src/ratings-fit.ts). Do not edit by hand. */
export const ${name}: ${type} = ${JSON.stringify(table)};
`,
  );
  execFileSync('pnpm', ['exec', 'prettier', '--write', out.pathname], { stdio: 'ignore' });
  return out;
};

const sig = (v: number) => Number(v.toPrecision(5));
const fitKey = (group: Row[], key: string): RatingFit => {
  const y = (rs: Row[]) => rs.map((r) => r.ratings[key] ?? 50);
  const train = group.filter((r) => r.league % 5 !== 4);
  const test = group.filter((r) => r.league % 5 === 4);
  const held = fitLinear(
    train.map((r) => r.x),
    y(train),
  );
  const predict = (c: number[], x: number[]) =>
    c.reduce((s, v, i) => s + v * (i ? x[i - 1]! : 1), 0);
  const actual = y(test);
  const sse = test.reduce((s, r, i) => s + (actual[i]! - predict(held, r.x)) ** 2, 0);
  const sst = actual.reduce((s, v) => s + (v - mean(actual)) ** 2, 0);
  const all = y(group);
  return {
    coef: fitLinear(
      group.map((r) => r.x),
      all,
    ).map(sig),
    mean: sig(mean(all)),
    priorSd: sig(sd(all)),
    residualSd: sig(Math.sqrt(sse / test.length)),
    r2: Math.round(1000 * (1 - sse / sst)) / 1000,
  };
};

const keysOf = (g: RatingGroup) => (g === 'G' ? GOALIE_RATINGS : SKATER_RATINGS);
const groups = Object.fromEntries(
  (['F', 'D', 'G'] as const).map((g) => [
    g,
    Object.fromEntries(keysOf(g).map((k) => [k, fitKey(rows[g], k)])),
  ]),
) as StatsToRatingsTable['groups'];
const specialTeams = Object.fromEntries(
  (['F', 'D'] as const).map((g) => [
    g,
    Object.fromEntries(SKATER_RATINGS.map((k) => [k, fitKey(specialRows[g], k)])),
  ]),
) as StatsToRatingsTable['specialTeams'];
const table: StatsToRatingsTable = {
  format: 'gm-stats-to-ratings',
  version: 3,
  source: `sim self-fit, ${leagues} leagues x 1 season, full samples (skaters ${FULL_SAMPLE.skater}, goalies ${FULL_SAMPLE.goalie} of ${seasonGames} games)`,
  groups,
  specialTeams,
};

const fromStatsFile = writeTable(
  'ratingsFromStatsTable.ts',
  './ratingsFromStats',
  'STATS_TO_RATINGS',
  'StatsToRatingsTable',
  table,
);

// Ratings to stats, fit in sample: the lines it draws are lab targets, not a forecast.
const fitRate = (g: RatingGroup, stat: string) => {
  const x = rates[g].map((r) => keysOf(g).map((k) => r.ratings[k] ?? 50));
  const y = rates[g].map((r) => r.y[stat]!);
  const coef = fitLinear(x, y);
  const sse = x.reduce(
    (s, xs, i) => s + (y[i]! - xs.reduce((a, v, j) => a + v * coef[j + 1]!, coef[0]!)) ** 2,
    0,
  );
  const sst = y.reduce((s, v) => s + (v - mean(y)) ** 2, 0);
  console.log(`  ${g} ${stat.padEnd(8)} R² ${(1 - sse / sst).toFixed(3)}`);
  return coef.map(sig);
};
console.log('\nRatings to stats (in sample):');
const statsOf = (g: RatingGroup) => (g === 'G' ? ['savePct'] : ['goals', 'assists']);
const toStats: RatingsToStatsTable = {
  format: 'gm-ratings-to-stats',
  version: 1,
  source: `sim self-fit, ${leagues} leagues x 1 season, the same full samples`,
  groups: Object.fromEntries(
    (['F', 'D', 'G'] as const).map((g) => [
      g,
      Object.fromEntries(statsOf(g).map((s) => [s, fitRate(g, s)])),
    ]),
  ) as RatingsToStatsTable['groups'],
};
const toStatsFile = writeTable(
  'ratingsToStatsTable.ts',
  './leagueLines',
  'RATINGS_TO_STATS',
  'RatingsToStatsTable',
  toStats,
);

console.log(
  `\nStats to ratings: ${leagues} leagues, ${((performance.now() - started) / 1000).toFixed(1)}s`,
);
console.log(
  'Held-out R² (share of the rating a full season explains) and error in rating points,\n' +
    'then with penalty-kill time and penalty minutes (skaters):\n',
);
for (const g of ['F', 'D', 'G'] as const) {
  console.log(`${g} (${rows[g].length} player seasons)`);
  for (const [k, f] of Object.entries(groups[g])) {
    const st = g === 'G' ? undefined : specialTeams[g][k]!;
    console.log(
      `  ${k.padEnd(16)} R² ${f.r2.toFixed(3).padStart(6)}   ±${f.residualSd.toFixed(1)} (spread ${f.priorSd.toFixed(1)})` +
        (st
          ? `   with PK/PIM R² ${st.r2.toFixed(3).padStart(6)}   ±${st.residualSd.toFixed(1)}`
          : ''),
    );
  }
}
console.log(`\nWrote ${fromStatsFile.pathname}\n  and ${toStatsFile.pathname}\n`);
